// Offline, deterministic conversion of the user-supplied static Pagoda.gltf.
// Original bytes remain in src/user-models/pagoda/source.gltf.gz; no network inputs.
import fs from 'node:fs';
import { pagodaRole } from './pagoda-material-rules.mjs';
import { gunzipSync, deflateSync } from 'node:zlib';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import * as THREE from 'three';
import { GLTFLoader } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { mergeGeometries } from 'three/examples/jsm/utils/BufferGeometryUtils.js';
const dir = fileURLToPath(new URL('../src/user-models/pagoda/', import.meta.url));
const source = gunzipSync(fs.readFileSync(dir+'source.gltf.gz'));
const json = JSON.parse(source.toString('utf8'));
if (json.animations?.length || json.skins?.length || json.materials?.length || json.images?.length || json.extensionsRequired?.length) throw Error('This converter only supports this static, untextured source; do not silently flatten other models.');
for (const b of json.buffers || []) if (!b.uri?.startsWith('data:application/octet-stream;base64,')) throw Error('External buffers are not allowed');
globalThis.ProgressEvent ||= class { constructor(type, options) { this.type=type;Object.assign(this,options); } };
const gltf = await new GLTFLoader().parseAsync(source.toString('utf8'), '');
const scene = gltf.scene;
scene.updateMatrixWorld(true);
const sourceBounds = new THREE.Box3().setFromObject(scene);
const center = sourceBounds.getCenter(new THREE.Vector3()), size=sourceBounds.getSize(new THREE.Vector3());
const geometries=[], parts=[];let vertexOffset=0;
scene.traverse(n=>{
  if(!n.isMesh)return;
  if(n.isSkinnedMesh || n.morphTargetInfluences?.length || n.matrixWorld.determinant()<=0)throw Error('Unsupported skin, morph or mirrored transform');
  const geo=n.geometry.clone();
  // Strip the index only if needed; both layouts are converted to explicit faces.
  const g=geo.index ? geo.toNonIndexed() : geo;
  if(g!==geo)geo.dispose();
  g.applyMatrix4(n.matrixWorld);
  g.translate(-center.x,-sourceBounds.min.y,-center.z);
  if(!g.getAttribute('normal'))g.computeVertexNormals();
  if(!g.getAttribute('uv'))g.setAttribute('uv',new THREE.BufferAttribute(new Float32Array(g.getAttribute('position').count*2),2));
  for(const key of Object.keys(g.attributes))if(!['position','normal','uv'].includes(key))g.deleteAttribute(key);
  const node=gltf.parser.associations.get(n)?.nodes;
  if (!Number.isInteger(node)) throw Error('Missing source node association');
  const name=json.nodes[node].name;
  g.computeBoundingBox();
  const count=g.getAttribute('position').count;
  parts.push({node,name,start:vertexOffset,count,...pagodaRole(name,node),bounds:{min:g.boundingBox.min.toArray().map(v=>+v.toFixed(5)),max:g.boundingBox.max.toArray().map(v=>+v.toFixed(5))}});
  vertexOffset+=count;
  geometries.push(g);
});
const merged=mergeGeometries(geometries,false);
if(!merged)throw Error('Cannot merge supplied mesh layouts');
const blocks=[],attributes={};let offset=0;
for(const name of ['position','normal','uv']){
  const a=merged.getAttribute(name),values=new Float32Array(a.count*a.itemSize);
  for(let i=0;i<a.count;i++)for(let k=0;k<a.itemSize;k++)values[i*a.itemSize+k]=a.getComponent(i,k);
  for(const v of values)if(!Number.isFinite(v))throw Error('Non-finite geometry');
  const buffer=Buffer.from(values.buffer);blocks.push(buffer);
  attributes[name]={offset,length:values.length,itemSize:a.itemSize};offset+=buffer.length;
}
const raw=Buffer.concat(blocks),compressed=deflateSync(raw,{level:9});
const manifest={format:1,sourceFile:'Pagoda.gltf',sourceSHA256:createHash('sha256').update(source).digest('hex'),sourceBounds:{min:sourceBounds.min.toArray(),max:sourceBounds.max.toArray(),size:size.toArray()},sourceNodes:json.nodes.length,sourceMeshes:geometries.length,triangles:merged.getAttribute('position').count/3,vertices:merged.getAttribute('position').count,materialsInSource:0,texturesInSource:0,animationsInSource:0,drawMeshes:1,attributes,rawBytes:raw.length,compressedBytes:compressed.length,packedSHA256:createHash('sha256').update(raw).digest('hex'),normalization:'center X/Z and bottom Y=0; source axes and proportions retained; no polygon reduction',license:'User supplied. Redistribution permission has not been verified; not a public-release license grant.'};
const chunks=compressed.toString('base64').match(/.{1,120}/g);
fs.writeFileSync(dir+'geometry.js', '// Generated by scripts/prepare-pagoda.mjs. Do not edit encoded geometry by hand.\nexport const PAGODA_INFO = '+JSON.stringify(manifest)+';\nexport const PAGODA_BYTES = '+JSON.stringify(chunks,null,0)+'.join(\'\');\n');
fs.writeFileSync(dir+'manifest.json',JSON.stringify(manifest,null,2)+'\n');
const roles={};for(const p of parts){const r=roles[p.role] ||= {parts:0,triangles:0};r.parts++;r.triangles+=p.count/3;}
fs.writeFileSync(dir+'parts.js','// Generated from source node associations; reviewed rules in scripts/pagoda-material-rules.mjs.\nexport const PAGODA_PARTS = '+JSON.stringify(parts.map(({node,name,start,count,role,grain})=>({node,name,start,count,role,...(grain?{grain}:{})})))+';\n');
fs.writeFileSync(dir+'materials-manifest.json',JSON.stringify({format:1,sourceSHA256:manifest.sourceSHA256,interpretation:'New authored wood variant, not recovered original materials. Source contains no materials.',drawMeshes:Object.keys(roles).length,roles,parts},null,2)+'\n');
for(const g of geometries)g.dispose();merged.dispose();
console.log(JSON.stringify(manifest,null,2));
