import assert from 'node:assert/strict';
import * as THREE from 'three';
import { bloomSelection, surfaceKey, objectSurfaces, surfaceContribution, SelectiveBloomPass } from '../src/selective-bloom.js';
import { RenderEffects, bloomSettings, BLOOM_DEFAULTS } from '../src/render-effects.js';
assert.deepEqual(bloomSettings(), BLOOM_DEFAULTS);
assert.equal(bloomSettings({ enabled: true }).mode, 'all');
assert.equal(bloomSettings({ mode: 'selective', windows: false }).windows, false);
assert.equal(bloomSettings({ mode: 'invented' }).mode, 'all');
assert.deepEqual(bloomSelection(null), { mode: 'auto', source: 'emission', gain: 2, parts: [] });
assert.equal(bloomSelection({ parts: new Array(300).fill('a'), gain: 100 }).parts.length, 1);
assert.equal(bloomSelection({ parts: Array.from({ length: 300 }, (_, i) => '' + i) }).parts.length, 256);
assert.equal(bloomSelection({ gain: Infinity }).gain, 2);
const mesh = new THREE.Mesh(new THREE.PlaneGeometry(2, 2), new THREE.MeshStandardMaterial({ emissive: 0xffffff }));
mesh.name = 'window'; mesh.material.userData.role = 'glass';
const so = { root: new THREE.Group(), params: {}, item: { catId: 'house' } }; so.root.add(mesh);
const app = { objects: [so], appearance: { roots: new WeakMap() }, stage: { scene: new THREE.Scene(), world: new THREE.Group(), composer: { removePass() {} } },
  lighting: { physical: { color: { gain: new THREE.Vector3(1, 1, 1) } } }, bus: { on() {}, emit() {} }, beginOp() {}, saveLocal() {} };
const surfaces = objectSurfaces(app, so); assert.equal(surfaces.length, 1); assert.ok(surfaces[0].window);
assert.deepEqual(surfaceContribution(bloomSelection(), surfaces[0], true), { kind: 'emission', gain: 1 });
assert.equal(surfaceContribution(bloomSelection(), surfaces[0], false), null);
assert.equal(surfaceContribution(bloomSelection({ mode: 'off' }), surfaces[0], true), null);
const policy = bloomSelection({ mode: 'custom', source: 'color', gain: 3, parts: [surfaces[0].key] });
assert.deepEqual(surfaceContribution(policy, surfaces[0], false), { kind: 'color', gain: 3 });
const clone = mesh.clone(); clone.geometry = mesh.geometry.clone(); clone.material = mesh.material.clone();
assert.equal(surfaceKey(clone, [0], 0, clone.material), surfaces[0].key, 'UUID leaked into structural reference');
const rootKey = surfaceKey(clone, [], 0, clone.material); clone.position.x = 9; assert.equal(surfaceKey(clone, [], 0, clone.material), rootKey, 'root placement leaked into surface identity');
clone.position.x = 1; assert.notEqual(surfaceKey(clone, [0], 0, clone.material), surfaces[0].key);
const effects = new RenderEffects(app);
assert.ok(effects.setObject(so, { mode: 'custom', parts: [surfaces[0].key] }));
so.locked = true; assert.equal(effects.setObject(so, { mode: 'off' }), false); so.locked = false;
effects.configure({ bloom: { enabled: true, mode: 'selective' } });
const pass = new SelectiveBloomPass(effects);
pass.setSize(400, 260);
assert.equal(pass.selectionTarget.width, 400); assert.equal(pass.renderTargetBright.width, 100);
let sourceDisposals = 0, cloneDisposals = 0;
mesh.material.addEventListener('dispose', () => sourceDisposals++);
const variant = pass.variant(mesh.material, { kind: 'emission', gain: 2 });
assert.notEqual(variant, mesh.material);
variant.addEventListener('dispose', () => cloneDisposals++);
const shader = { fragmentShader: 'void main(){vec4 diffuseColor=vec4(1.0);vec3 totalEmissiveRadiance=vec3(2.0);\n#include <tonemapping_fragment>\n#include <fog_fragment>\n}', uniforms: {} };
variant.onBeforeCompile(shader, {});
assert.ok(shader.fragmentShader.includes('totalEmissiveRadiance * 2.00000000'));
assert.ok(!shader.fragmentShader.includes('mix( gl_FragColor.rgb, fogColor, fogFactor )'));
assert.ok(shader.fragmentShader.includes('gl_FragColor.rgb *= 1.0 - fogFactor'));
assert.equal(pass.variant(mesh.material, { kind: 'emission', gain: 2 }), variant);
mesh.material.emissiveIntensity = 0; pass.variant(mesh.material, { kind: 'emission', gain: 2 }); assert.equal(variant.emissiveIntensity, 0);
pass.epoch++; pass.prune(); assert.equal(cloneDisposals, 1); assert.equal(pass.variants.size, 0); assert.equal(sourceDisposals, 0);
const bad = new THREE.ShaderMaterial(); const fallback = pass.variant(bad, { kind: 'color', gain: 8 }); assert.equal(fallback.color.getHex(), 0); assert.equal(pass.stats.unsupported, 1);
pass.dispose(); pass.materialHighPassFilter.dispose();
mesh.geometry.dispose(); mesh.material.dispose(); clone.geometry.dispose(); clone.material.dispose(); bad.dispose();
console.log('PASS legacy defaults/mode clamps, scope normalization/limits, structural references, auto/custom/exclude, immutable emission/color variants, fog attenuation, runtime radiance updates, unsupported shader fail-closed, release/source ownership');
