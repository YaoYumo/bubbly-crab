import assert from 'node:assert/strict';
import fs from 'node:fs';
import {gunzipSync,inflateSync} from 'node:zlib';
import {createHash} from 'node:crypto';
import * as T from 'three';
import {buildPagoda,PAGODA_INFO} from '../src/user-models/pagoda/build.js';
import {PAGODA_BYTES} from '../src/user-models/pagoda/geometry.js';
const sha=b=>createHash('sha256').update(b).digest('hex');
const original=gunzipSync(fs.readFileSync('src/user-models/pagoda/source.gltf.gz'));
assert.equal(sha(original),PAGODA_INFO.sourceSHA256);
const source=JSON.parse(original);assert.equal(source.materials?.length || 0,0);assert.equal(source.images?.length || 0,0);
assert.equal(sha(inflateSync(Buffer.from(PAGODA_BYTES,'base64'))),PAGODA_INFO.packedSHA256);
const triangleCount=source.meshes.flatMap(m=>m.primitives).reduce((n,p)=>n+source.accessors[p.indices].count/3,0);
const a=buildPagoda(),b=buildPagoda();const box=g=>{g.updateMatrixWorld(true);return new T.Box3().setFromObject(g);};
const bb=box(a),size=bb.getSize(new T.Vector3());
assert.equal(a.children.length,1);assert.equal(a.children[0].geometry.attributes.position.count/3,triangleCount);assert.equal(triangleCount,34392);
assert.ok(Math.abs(bb.min.y)<1e-5);assert.ok(Math.abs(bb.min.x+bb.max.x)<1e-5);assert.ok(Math.abs(bb.min.z+bb.max.z)<1e-5);
size.toArray().forEach((v,i)=>assert.ok(Math.abs(v-PAGODA_INFO.sourceBounds.size[i])<1e-5));
const changed=buildPagoda({height:12,color:'#884422'});assert.ok(Math.abs(box(changed).getSize(new T.Vector3()).y-12)<1e-5);
assert.equal(changed.children[0].material.color.getHexString(),'884422');
assert.notEqual(a.children[0].material,b.children[0].material);assert.notEqual(a.children[0].geometry.attributes.position.array.buffer,b.children[0].geometry.attributes.position.array.buffer);
const b0=b.children[0].geometry.attributes.position.getX(0);a.children[0].geometry.attributes.position.setX(0,999);
a.children[0].geometry.dispose();a.children[0].material.dispose();assert.equal(b.children[0].geometry.attributes.position.getX(0),b0);
assert.equal(buildPagoda().children[0].geometry.attributes.position.getX(0),b0);
for(const h of [NaN,Infinity,'bad'])assert.ok(Math.abs(box(buildPagoda({height:h})).getSize(new T.Vector3()).y-size.y)<1e-5);
assert.ok(box(buildPagoda({height:999})).getSize(new T.Vector3()).y<120.001);
for(const v of b.children[0].geometry.attributes.normal.array)assert.ok(Number.isFinite(v));
console.log('PASS Pagoda source integrity, all 34392 triangles, source proportions, floor origin, resizing/color, per-object geometry/material ownership and disposal');
