import assert from 'node:assert/strict';
import {detectRoadParcels,inParcel,footprintFits} from '../src/road-parcels.js';
const road=points=>({points,half:4});
const square=road([[-50,-50],[50,-50],[50,50],[-50,50],[-50,-50]]);
assert.equal(detectRoadParcels([road([[-50,0],[50,0]])]).length,0);
assert.equal(detectRoadParcels([road([[-50,0],[50,0]]),road([[0,-50],[0,0]])]).length,0);
const enclosed=detectRoadParcels([square]);assert.equal(enclosed.length,1);
assert.ok(Math.abs(enclosed[0].area-88**2)<1e-4);
assert.equal(detectRoadParcels([square,road([[0,-60],[0,60]])]).length,2);
assert.equal(detectRoadParcels([square,road([[0,-60],[0,60]]),road([[-60,0],[60,0]])]).length,4);
const island=detectRoadParcels([square,road([[-10,0],[10,0]])]);
assert.equal(island.length,1);assert.equal(island[0].polygon.length,2);assert.equal(inParcel(0,0,island[0].polygon),false);
assert.equal(footprintFits({minX:-2,maxX:2,minZ:-2,maxZ:2},island[0].polygon),false);
assert.equal(footprintFits({minX:20,maxX:25,minZ:20,maxZ:25},island[0].polygon),true);
const u=[[[0,0],[100,0],[100,100],[70,100],[70,30],[30,30],[30,100],[0,100],[0,0]]];
for(const [x,z]of [[10,10],[90,10],[90,80],[10,80]])assert.equal(inParcel(x,z,u),true);
assert.equal(footprintFits({minX:10,maxX:90,minZ:10,maxZ:80},u),false,'must test whole footprint, not just 4 corners');
const reverse=road([...square.points].reverse());
assert.equal(detectRoadParcels([reverse])[0].id,enclosed[0].id,'stable ID after reversed control points');
assert.equal(detectRoadParcels([square,square,square])[0].id,enclosed[0].id,'coincident roads stay robust');
const rotated={half:4,points:square.points.map(([x,z])=>[x*Math.cos(.7)-z*Math.sin(.7),x*Math.sin(.7)+z*Math.cos(.7)])};
assert.equal(detectRoadParcels([rotated]).length,1);
console.log('PASS: open/T=0, closed=1, split=2/4, interior road holes, whole-footprint containment, rotation, stable IDs, coincident geometry');
